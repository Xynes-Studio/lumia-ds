#!/usr/bin/env node
// @ts-check

const fs = require('node:fs');
const path = require('node:path');
const { readSvgDirectory, renderComponent } = require('./lib/svg-import');

/** @typedef {{ file: string, iconId: string, componentName: string, source: string }} IconEntry */

/** @param {string} value */
function toPascalCase(value) {
  return value
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((segment) => segment[0].toUpperCase() + segment.slice(1))
    .join('');
}

/** @param {string} value */
function toKebabCase(value) {
  return value
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[_\s]+/g, '-')
    .replace(/-+/g, '-')
    .toLowerCase();
}

/** @param {IconEntry[]} entries */
function renderIndex(entries) {
  return `// Auto-generated by lumia-icon-import. Do not edit by hand.
${entries.map(({ componentName }) => `export { ${componentName} } from './icons/${componentName}';`).join('\n')}
`;
}

/** @param {IconEntry[]} entries */
function renderRegistry(entries) {
  return `// Auto-generated by lumia-icon-import. Do not edit by hand.
import type { RegisterIconFn } from '../types';
${entries.map(({ componentName }) => `import { ${componentName} } from './icons/${componentName}';`).join('\n')}

export function registerGeneratedIcons(registerIcon: RegisterIconFn) {
${entries.map(({ iconId, componentName }) => `  registerIcon(${JSON.stringify(iconId)}, ${componentName});`).join('\n')}
}
`;
}

/** Validate and render the entire batch before replacing generated components.
 * @param {string} sourceDir
 * @param {string} iconsPackageRoot
 */
function importIcons(sourceDir, iconsPackageRoot) {
  const inputs = readSvgDirectory(sourceDir);
  const componentNames = new Set();
  const iconIds = new Set();
  const entries = inputs.map(({ file, baseName, svg }) => {
    const iconId = toKebabCase(baseName);
    const pascalName = toPascalCase(baseName);
    const componentName = `${/^\d/.test(pascalName) ? 'Icon' : ''}${pascalName}Icon`;
    if (componentNames.has(componentName) || iconIds.has(iconId)) {
      throw new Error('SVG filenames produce duplicate icon names');
    }
    componentNames.add(componentName);
    iconIds.add(iconId);
    return {
      file,
      iconId,
      componentName,
      source: renderComponent(componentName, svg),
    };
  });

  const generatedRoot = path.join(iconsPackageRoot, 'src', 'generated');
  const componentsDir = path.join(generatedRoot, 'icons');
  fs.mkdirSync(componentsDir, { recursive: true });
  for (const file of fs.readdirSync(componentsDir)) {
    if (file.endsWith('.tsx')) fs.unlinkSync(path.join(componentsDir, file));
  }
  for (const { file, componentName, source } of entries) {
    fs.writeFileSync(
      path.join(componentsDir, `${componentName}.tsx`),
      source,
      'utf8',
    );
    console.log(`Generated ${componentName} from ${file}`);
  }
  fs.writeFileSync(
    path.join(generatedRoot, 'index.ts'),
    renderIndex(entries),
    'utf8',
  );
  fs.writeFileSync(
    path.join(generatedRoot, 'registry.ts'),
    renderRegistry(entries),
    'utf8',
  );
  console.log(
    `Wrote ${entries.length} icon(s) to ${path.relative(process.cwd(), generatedRoot)}`,
  );
}

/** @param {string[]} args */
function run(args) {
  const [source, output] = args;
  if (!source || source === '--help' || args.length > 2) {
    console.error(
      'Usage: lumia-icon-import <svg-source-folder> [icons-package-root]',
    );
    return 1;
  }
  try {
    importIcons(
      path.resolve(source),
      path.resolve(output || path.join('packages', 'icons')),
    );
    return 0;
  } catch (error) {
    console.error(error instanceof Error ? error.message : 'SVG import failed');
    return 1;
  }
}

if (require.main === module) process.exitCode = run(process.argv.slice(2));
module.exports = { importIcons, run };
